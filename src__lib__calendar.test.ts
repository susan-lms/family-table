import { addDays, addMonths, daysBetween, makeRange, monthGrid, weekOf, weekdayMon0, MAX_RANGE_DAYS } from "./calendar";
let n = 0;
const eq = (a: unknown, b: unknown, m: string) => { if (JSON.stringify(a) !== JSON.stringify(b)) { console.error("FAIL -", m, JSON.stringify(a), "!=", JSON.stringify(b)); process.exit(1); } n++; console.log("ok -", m); };
eq(weekdayMon0("2026-10-12"), 0, "12 Oct 2026 is a Monday");
eq(weekdayMon0("2026-10-18"), 6, "18 Oct 2026 is a Sunday");
eq(addDays("2026-10-30", 3), "2026-11-02", "adding days crosses a month");
eq(addDays("2026-12-30", 3), "2027-01-02", "adding days crosses a year");
eq(addMonths("2026-12", 1), "2027-01", "next month crosses a year");
eq(addMonths("2026-01", -1), "2025-12", "earlier month crosses a year");
eq(weekOf("2026-10-15"), { from: "2026-10-12", to: "2026-10-18" }, "week of a Thursday is Monday to Sunday");
eq(makeRange("2026-10-20", "2026-10-14"), { from: "2026-10-14", to: "2026-10-20" }, "range works when the second tap is earlier");
const long = makeRange("2026-10-12", "2026-12-30");
eq(daysBetween(long.from, long.to) + 1, MAX_RANGE_DAYS, "a long range is cut to 31 days");
const g = monthGrid("2026-10");
eq(g.length % 7, 0, "calendar grid has whole weeks");
eq(g.filter(Boolean).length, 31, "October has 31 days");
eq(g[0], null, "1 Oct 2026 is a Thursday, so Monday is empty");
eq(g[3], "2026-10-01", "1 Oct 2026 sits in the Thursday column");
console.log(n, "passed");
