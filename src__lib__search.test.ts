import { parseQuery, matchScore } from "./search";
import { catalog, EXCLUDED_CUISINES } from "./sample-data";
import { CUISINES, TYPES } from "./browse";
let fail = 0;
const ok = (c: boolean, m: string) => { if (!c) { fail++; console.error("FAIL:", m); } };
const pool = catalog.filter((r) => !EXCLUDED_CUISINES.includes(r.cuisine));
const find = (q: string) => {
  const p = parseQuery(q);
  const ct = CUISINES.find((c) => c.id === (p.cuisineId ?? "all"))!.test;
  const tt = TYPES.find((t) => t.id === (p.typeId ?? "all"))!.test;
  return pool.filter((r) => ct(r) && tt(r) && matchScore(r, p.tokens) > 0);
};
ok(parseQuery("Chinese").cuisineId === "chinese", "chinese -> tab");
ok(parseQuery("粤菜").cuisineId === "cantonese", "zh cantonese");
ok(parseQuery("thai soup").cuisineId === "thai" && parseQuery("thai soup").typeId === "soup", "thai soup");
ok(parseQuery("chinese pork").tokens.join() === "pork", "leftover pork");
ok(parseQuery("").cuisineId === null, "empty");
const chinese = find("chinese");
ok(chinese.length > 100 && chinese.every((r) => r.cuisine === "Chinese"), `chinese all (${chinese.length})`);
const pork = find("pork");
ok(pork.length > 30, `pork many (${pork.length})`);
ok(pork.every((r) => matchScore(r, ["pork"]) > 0), "pork match");
ok(find("prawn").length === find("shrimp").length && find("prawn").length > 5, "prawn=shrimp");
ok(find("tofu").length > 10, "tofu");
ok(find("chinese pork").length > 5 && find("chinese pork").length < pork.length, "chinese pork narrower");
ok(find("豆腐").length > 5, "zh tofu");
ok(find("xyzzy").length === 0, "no match");
ok(find("japanese noodles").every((r) => r.cuisine === "Japanese"), "japanese noodles");
ok(find("mushrooms").length === find("mushroom").length, "plural");
console.log(`pork=${pork.length} chinese=${chinese.length} tofu=${find("tofu").length}`);
console.log(fail ? `${fail} FAILED` : "search: all passed");
process.exit(fail ? 1 : 0);
